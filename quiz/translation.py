def uz_latin_to_cyrillic(text):
    if not text:
        return text
    table = [
        ("O'", 'Ў'), ("o'", 'ў'), ("O`", 'Ў'), ("o`", 'ў'),
        ("G'", 'Ғ'), ("g'", 'ғ'), ("G`", 'Ғ'), ("g`", 'ғ'),
        ('SH', 'Ш'), ('Sh', 'Ш'), ('sh', 'ш'),
        ('CH', 'Ч'), ('Ch', 'Ч'), ('ch', 'ч'),
        ('NG', 'НГ'), ('Ng', 'Нг'), ('ng', 'нг'),
        ('TS', 'Ц'), ('Ts', 'Ц'), ('ts', 'ц'),
        ('YA', 'Я'), ('Ya', 'Я'), ('ya', 'я'),
        ('YO', 'Ё'), ('Yo', 'Ё'), ('yo', 'ё'),
        ('YU', 'Ю'), ('Yu', 'Ю'), ('yu', 'ю'),
        ('A', 'А'), ('a', 'а'),
        ('B', 'Б'), ('b', 'б'),
        ('D', 'Д'), ('d', 'д'),
        ('E', 'Е'), ('e', 'е'),
        ('F', 'Ф'), ('f', 'ф'),
        ('G', 'Г'), ('g', 'г'),
        ('H', 'Ҳ'), ('h', 'ҳ'),
        ('I', 'И'), ('i', 'и'),
        ('J', 'Ж'), ('j', 'ж'),
        ('K', 'К'), ('k', 'к'),
        ('L', 'Л'), ('l', 'л'),
        ('M', 'М'), ('m', 'м'),
        ('N', 'Н'), ('n', 'н'),
        ('O', 'О'), ('o', 'о'),
        ('P', 'П'), ('p', 'п'),
        ('Q', 'Қ'), ('q', 'қ'),
        ('R', 'Р'), ('r', 'р'),
        ('S', 'С'), ('s', 'с'),
        ('T', 'Т'), ('t', 'т'),
        ('U', 'У'), ('u', 'у'),
        ('V', 'В'), ('v', 'в'),
        ('X', 'Х'), ('x', 'х'),
        ('Y', 'Й'), ('y', 'й'),
        ('Z', 'З'), ('z', 'з'),
        ("'", 'ъ'),
    ]
    result = text
    for lat, cyr in table:
        result = result.replace(lat, cyr)
    return result
